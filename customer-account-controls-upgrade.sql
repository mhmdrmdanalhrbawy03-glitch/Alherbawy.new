alter table public.profiles
  add column if not exists account_status text not null default 'active',
  add column if not exists warning_message text,
  add column if not exists is_verified boolean not null default false,
  add column if not exists last_seen_at timestamptz;

alter table public.profiles drop constraint if exists profiles_account_status_check;
alter table public.profiles add constraint profiles_account_status_check
  check (account_status in ('active','warned','suspended','banned'));

create table if not exists public.customer_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_name text not null,
  created_at timestamptz not null default now()
);

alter table public.customer_activity enable row level security;
drop policy if exists "admins read customer activity" on public.customer_activity;
create policy "admins read customer activity" on public.customer_activity
  for select to authenticated using (public.is_admin());

create or replace function public.record_customer_activity(activity_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if activity_name not in ('login','order_created','profile_view') then
    raise exception 'Unsupported activity';
  end if;
  insert into public.customer_activity(user_id, activity_name)
  values (auth.uid(), activity_name);
  update public.profiles set last_seen_at = now() where id = auth.uid();
end;
$$;

revoke all on function public.record_customer_activity(text) from public;
grant execute on function public.record_customer_activity(text) to authenticated;

-- لا تسمح للعميل بتعديل حالة حسابه أو علامة التوثيق؛ التعديل متاح للمدير فقط.
drop policy if exists "admins update customer profiles" on public.profiles;
create policy "admins update customer profiles" on public.profiles
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- السماح بتسجيل النشاط عبر الدالة فقط، ومنع القراءة المباشرة للعملاء.
grant select on public.customer_activity to authenticated;
